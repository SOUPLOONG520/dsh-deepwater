// build-client.mjs - regenerates client.js from the sources in src/.
//
// The Host half injects those files as text into every index the web server
// renders, which reaches the browser Web UI but NOT the desktop app: the
// desktop app renders its own bundled SPA (dsh-app://app/assets/index-*.js)
// and only picks up plugins that ship a browser entry.
//
// So the same files are also shipped as a browser entry. The text is embedded
// verbatim (JSON-encoded) instead of copied by hand, so src/ stays the single
// source of truth: edit it, run this script, reload.
//
//   node build-client.mjs

import { readFileSync, writeFileSync } from 'node:fs'
import { DEFAULTS, PRESETS } from './entry.js'

const CSS = readFileSync(new URL('./src/polish.css', import.meta.url), 'utf8')
const SURFACE = readFileSync(new URL('./src/polish.js', import.meta.url), 'utf8')
const AMBIENCE = readFileSync(new URL('./src/ambient.js', import.meta.url), 'utf8')
const API = readFileSync(new URL('./src/deepwater.js', import.meta.url), 'utf8')
const ROUTE = '/plugins/dsh-deepwater'

const CLIENT = `/*
 * dsh-deepwater - Client half.
 *
 * GENERATED by build-client.mjs from src/polish.css, src/polish.js,
 * src/ambient.js and src/deepwater.js. Do not edit by hand: edit the sources
 * and run \`node build-client.mjs\` instead.
 *
 * The desktop app does not render the index the Host half injects into - it
 * boots its own bundled SPA - so a Host-side index injection never reaches it.
 * This browser entry installs the very same sources there: the surface layer
 * first, the ambience layer next, and the shared API last, exactly as the
 * head rows do on the web.
 *
 * The disposer is the one-click switch: it tears both layers down and gives
 * the app its own frame back.
 */

window.__ModuleLoader__.load({
  id: 'dsh-deepwater',
  factory() {
    var DEFAULTS = ${JSON.stringify(DEFAULTS, null, 2)}
    var PRESETS = ${JSON.stringify(PRESETS)}
    var CSS = ${JSON.stringify(CSS)}
    var SURFACE = ${JSON.stringify(SURFACE)}
    var AMBIENCE = ${JSON.stringify(AMBIENCE)}
    var API = ${JSON.stringify(API)}
    var ROUTE = ${JSON.stringify(ROUTE)}

    function surfaceConfig(settings) {
      return { enabled: true, preset: settings.preset, base: ROUTE }
    }

    function ambienceConfig(settings) {
      return {
        enabled: true,
        background: settings.background,
        deepBackground: settings.deepBackground,
        particles: settings.particles,
        glow: settings.glow,
        keyGlow: settings.keyGlow,
        transitions: settings.transitions,
        activeRow: settings.activeRow,
        respectReducedMotion: settings.respectReducedMotion,
        diagnostics: settings.diagnostics,
        base: ROUTE,
      }
    }

    function run(text) {
      var script = document.createElement('script')
      script.dataset.plugin = 'dsh-deepwater'
      script.textContent = text
      ;(document.head || document.documentElement).appendChild(script)
      script.remove()
    }

    function restore() {
      try {
        if (globalThis.__DSH_VISUAL_POLISH__ && globalThis.__DSH_VISUAL_POLISH__.detach) {
          globalThis.__DSH_VISUAL_POLISH__.detach()
        }
      } catch (error) {
        console.warn('[deepwater] client half: the surface layer did not detach cleanly', error)
      }
      try {
        if (globalThis.__DSH_AMBIENT_FX__ && globalThis.__DSH_AMBIENT_FX__.stop) {
          globalThis.__DSH_AMBIENT_FX__.stop()
        }
      } catch (error) {
        console.warn('[deepwater] client half: the ambience layer did not stop cleanly', error)
      }
    }

    function install(settings) {
      globalThis.__DSH_DEEPWATER_CFG__ = settings
      globalThis.__DSH_DEEPWATER_BASE__ = ROUTE
      globalThis.__DSH_POLISH_CFG__ = surfaceConfig(settings)
      globalThis.__DSH_POLISH_CSS__ = CSS
      if (settings.ambience !== false) {
        globalThis.__DSH_AMBIENT_FX_CFG__ = ambienceConfig(settings)
      }
      run(SURFACE)
      if (settings.ambience !== false) run(AMBIENCE)
      run(API)
    }

    function same(a, b) {
      var keys = Object.keys(DEFAULTS)
      for (var i = 0; i < keys.length; i++) {
        if (a[keys[i]] !== b[keys[i]]) return false
      }
      return true
    }

    return {
      inject: [],
      apply(ctx) {
        return ctx.effect(() => {
          if (globalThis.__DSH_DEEPWATER__ && globalThis.__DSH_DEEPWATER__.active) {
            console.info('[deepwater] client half: already active, skipping')
            return () => {}
          }

          var settings = Object.assign({}, DEFAULTS)
          install(settings)
          console.info('[deepwater] client half active; preset=' + settings.preset)

          // The desktop app never sees the Host's index injection, so the live
          // settings are read back over the plugin's own route. The baked
          // defaults are already on screen by then, so a profile that changed
          // one value swaps it in without a flash of the unstyled app.
          try {
            globalThis.fetch(ROUTE + '/settings', { cache: 'no-store' })
              .then(function (res) { return res && res.ok ? res.json() : null })
              .then(function (payload) {
                if (!payload || !payload.settings) return
                var live = Object.assign({}, DEFAULTS, payload.settings)
                if (same(live, settings)) return
                restore()
                install(live)
                settings = live
                console.info('[deepwater] client half: applied the live settings')
              })
              .catch(function () { /* the baked defaults stand */ })
          } catch (error) {
            console.info('[deepwater] client half: the live settings were not reachable', error)
          }

          return () => { restore() }
        })
      },
    }
  },
})
`

writeFileSync(new URL('./client.js', import.meta.url), CLIENT, 'utf8')
console.log('client.js written (' + CLIENT.length + ' bytes)')
